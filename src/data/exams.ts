export function getExamPaperBlueprint(
  examId: string,
  fallback?: Partial<Pick<MockTest, 'questionCount' | 'durationMinutes' | 'totalMarks' | 'negativeMark' | 'sections'>>,
): ExamPaperBlueprint {
  const override = EXAM_BLUEPRINT_OVERRIDES[examId];
  if (override) {
    return override;
  }

  const sections =
    fallback?.sections && fallback.sections.length > 0
      ? fallback.sections
      : [{en: 'General Section', hi: 'सामान्य अनुभाग'}];

  const totalQuestions =
    EXAM_DEFAULT_QUESTION_COUNTS[examId] ??
    (fallback?.questionCount && fallback.questionCount >= 20
      ? fallback.questionCount
      : 100);

  const baseCount = Math.floor(totalQuestions / sections.length);
  let remainder = totalQuestions - baseCount * sections.length;

  const sectionBlueprints: ExamSectionBlueprint[] = sections.map((section) => {
    const extra = remainder > 0 ? 1 : 0;
    if (remainder > 0) remainder -= 1;
    return {
      section,
      questionCount: baseCount + extra,
    };
  });

  return {
    totalQuestions,
    durationMinutes: fallback?.durationMinutes ?? 90,
    totalMarks: fallback?.totalMarks ?? 100,
    negativeMark: fallback?.negativeMark ?? 0.25,
    sections: sectionBlueprints,
  };
}

/**
 * Generates 90 Mock Tests per Exam / Stage Pack:
 * - Tests 1..3: Free Full Mocks (₹0)
 * - Tests 4..90: 87 Paid Mocks included in the ₹49 Exam/Stage Pack (or ₹299 Category Mega Bundle)
 */
function buildStandardTests(
  examId: string,
  examShort: string,
  examNameHi: string,
  duration: number,
  totalMarks: number,
  negativeMark: number,
  sections: BilingualText[],
  freeQuestionIds: string[] = CORE_SAMPLE_QUESTION_IDS,
  paidQuestionIds: string[] = ALL_MIXED_SAMPLE_QUESTION_IDS,
): MockTest[] {
  const blueprint = getExamPaperBlueprint(examId, {
    durationMinutes: duration,
    totalMarks,
    negativeMark,
    sections,
  });
  const tests: MockTest[] = [];

  for (let i = 1; i <= 3; i++) {
    tests.push({
      id: `${examId}-free-${i}`,
      examId,
      title: {
        en: `${examShort} Free Full Mock Test #${i}`,
        hi: `${examNameHi} निःशुल्क पूर्ण मॉक टेस्ट #${i}`,
      },
      durationMinutes: blueprint.durationMinutes,
      totalMarks: blueprint.totalMarks,
      negativeMark: blueprint.negativeMark,
      questionCount: blueprint.totalQuestions,
      tier: 'free',
      priceInr: 0,
      sections: blueprint.sections.map((s) => s.section),
      questionIds: freeQuestionIds,
    });
  }

  for (let n = 1; n <= 87; n++) {
    const testNum = n + 3;
    const labelEn =
      n <= 37
        ? `Full Length Mock Test #${testNum}`
        : n <= 67
          ? `New Pattern Speed Test #${testNum}`
          : `PYQ Pattern Mock Test #${testNum}`;
    const labelHi =
      n <= 37
        ? `पूर्ण मॉक टेस्ट #${testNum}`
        : n <= 67
          ? `नया पैटर्न स्पीड टेस्ट #${testNum}`
          : `विगत वर्ष पैटर्न टेस्ट #${testNum}`;

    tests.push({
      id: `${examId}-single-${n}`,
      examId,
      title: {
        en: `${examShort} ${labelEn}`,
        hi: `${examNameHi} ${labelHi}`,
      },
      durationMinutes: blueprint.durationMinutes,
      totalMarks: blueprint.totalMarks,
      negativeMark: blueprint.negativeMark,
      questionCount: blueprint.totalQuestions,
      tier: 'single',
      priceInr: 49,
      sections: blueprint.sections.map((s) => s.section),
      questionIds: paidQuestionIds,
    });
  }

  return tests;
}

